#!/usr/bin/env bash
#
# Starts three throwaway SSH test hosts on the CI runner's loopback interface.
#
# Usage:
#   sudo bash test/ci/setup-live-hosts.sh [path/to/test_ed25519.pub]
#
# The hosts mirror the contract in test/certs/README.md:
#
#   server1  127.0.0.10  tester, nopasswd, suuser, kbduser (keyboard-interactive)
#   server2  127.0.0.11  tester, nopasswd (NOPASSWD sudo), suuser
#   server3  127.0.0.12  tester, nopasswd, suuser
#
# The instances listen on port 2222 by default, because the runner image already
# runs its own sshd on 0.0.0.0:22. Set LIVE_SSH_PORT to change it.
#
# This script is meant for an ephemeral GitHub Actions runner. It creates OS
# users, installs the test public key, writes sudoers and sshd configs, and
# starts one sshd per address. It changes the runner's sudo/sshd state, so do
# not run it on a machine you care about.
#
# The private key is generated by the workflow and is never committed. Pass its
# matching `.pub` path as the first argument.
set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
  echo "setup-live-hosts.sh must run as root (use sudo)." >&2
  exit 1
fi

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
public_key_path=${1:-"$repo_root/test/certs/test_ed25519.pub"}

if [ ! -f "$public_key_path" ]; then
  echo "Public key not found: $public_key_path" >&2
  exit 1
fi
public_key=$(cat "$public_key_path")

test_user=${TEST_USER:-tester}
test_password=${TEST_PASSWORD:-password}
nopasswd_user=${NOPASSWD_USER:-nopasswd}
nopasswd_password=${NOPASSWD_PASSWORD:-nopasswdpassword}
su_user=${SU_USER:-suuser}
su_password=${SU_PASSWORD:-secondpassword}
kbd_user=${KBD_USER:-kbduser}
kbd_password=${KBD_PASSWORD:-kbdpassword}

# The runner's own sshd owns 0.0.0.0:22, so the test instances use 2222.
live_port=${LIVE_SSH_PORT:-2222}

users=("$test_user" "$nopasswd_user" "$su_user" "$kbd_user")

# The runner image ships openssh-server, but install it if a minimal image is
# used instead.
if ! command -v sshd >/dev/null 2>&1; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq openssh-server >/dev/null
fi

# OpenSSH 9.8+ splits the listener from the per-connection `sshd-session` and
# derives the session binary from argv[0]. Calling `sshd` through PATH leaves
# argv[0] relative, which fails with "sshd requires execution with an absolute
# path". Resolve the binary once and use that everywhere.
sshd_bin=$(command -v sshd)
case "$sshd_bin" in
  /*) ;;
  *)
    echo "sshd must resolve to an absolute path, got: $sshd_bin" >&2
    exit 1
    ;;
esac

# Stop any instances from a previous run so the script is idempotent.
for pidfile in /run/ssh2shell/sshd_*.pid; do
  [ -f "$pidfile" ] || continue
  kill "$(cat "$pidfile")" 2>/dev/null || true
done

for user in "${users[@]}"; do
  if ! id -u "$user" >/dev/null 2>&1; then
    useradd -m -U -s /bin/bash "$user"
  fi
done

# Password sudo for tester and nopasswd; NOPASSWD sudo only for nopasswd. suuser
# must stay out of the sudo group so the `su` test is meaningful.
getent group sudo >/dev/null || groupadd sudo
usermod -aG sudo "$test_user"
usermod -aG sudo "$nopasswd_user"
if id -nG "$su_user" | tr ' ' '\n' | grep -qx sudo; then
  gpasswd -d "$su_user" sudo >/dev/null
fi

{
  printf '%s:%s\n' "$test_user" "$test_password"
  printf '%s:%s\n' "$nopasswd_user" "$nopasswd_password"
  printf '%s:%s\n' "$su_user" "$su_password"
  printf '%s:%s\n' "$kbd_user" "$kbd_password"
} | chpasswd

for user in "${users[@]}"; do
  home=$(getent passwd "$user" | cut -d: -f6)
  group=$(id -gn "$user")
  install -d -m 700 -o "$user" -g "$group" "$home/.ssh"
  printf '%s\n' "$public_key" > "$home/.ssh/authorized_keys"
  chown "$user:$group" "$home/.ssh/authorized_keys"
  chmod 600 "$home/.ssh/authorized_keys"
done

sudoers_file=/etc/sudoers.d/90-ssh2shell-nopasswd
printf '%s ALL=(ALL) NOPASSWD:ALL\n' "$nopasswd_user" > "$sudoers_file"
chmod 440 "$sudoers_file"
visudo -cf "$sudoers_file" >/dev/null

install -d -m 700 /etc/ssh/ssh2shell
install -d -m 755 /run/sshd
install -d -m 755 /run/ssh2shell
install -d -m 755 /var/log/ssh2shell

start_host() {
  local octet=$1
  local address="127.0.0.$octet"
  local host_key="/etc/ssh/ssh2shell/host_${octet}_ed25519"
  local config="/etc/ssh/ssh2shell/sshd_${octet}.conf"
  local log="/var/log/ssh2shell/sshd_${octet}.log"

  if [ ! -f "$host_key" ]; then
    ssh-keygen -q -t ed25519 -N '' -C "ssh2shell-ci-$octet" -f "$host_key"
  fi
  chmod 600 "$host_key"

  cat > "$config" <<EOF
Port $live_port
ListenAddress $address
HostKey $host_key
PidFile /run/ssh2shell/sshd_${octet}.pid
PasswordAuthentication yes
KbdInteractiveAuthentication yes
UsePAM yes
PermitRootLogin no
AllowUsers ${users[*]}
AuthorizedKeysFile .ssh/authorized_keys
AllowTcpForwarding yes
X11Forwarding no
PrintMotd no
UseDNS no
Subsystem sftp internal-sftp
EOF

  # kbduser proves keyboard-interactive: password auth is disabled for it, so
  # the client must answer the PAM challenge.
  if [ "$octet" = 10 ]; then
    cat >> "$config" <<EOF

Match User $kbd_user
    PasswordAuthentication no
EOF
  fi

  chmod 600 "$config"
  "$sshd_bin" -t -f "$config"
  "$sshd_bin" -f "$config" -E "$log"

  for _ in $(seq 1 50); do
    if ss -ltnH | grep -q "$address:$live_port"; then
      return 0
    fi
    sleep 0.2
  done

  echo "sshd did not listen on $address:$live_port" >&2
  cat "$log" >&2 || true
  return 1
}

start_host 10
start_host 11
start_host 12

cat <<EOF
Live test hosts are ready on port $live_port:
  server1  127.0.0.10  users: ${users[*]}
  server2  127.0.0.11  users: ${users[*]} (${nopasswd_user}: NOPASSWD sudo)
  server3  127.0.0.12  users: ${users[*]}
EOF
